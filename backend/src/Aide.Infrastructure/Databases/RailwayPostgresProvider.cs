using System.Text.Json;
using Aide.Domain.Databases;
using Aide.Domain.Deployments;
using Aide.Domain.Entities;
using Aide.Domain.Platforms;
using Aide.Infrastructure.Platforms;
using static Aide.Infrastructure.Deployments.PlatformDeploymentCalls;

namespace Aide.Infrastructure.Databases;

/// <summary>
/// FR-152, §4.21 Railway Postgres in the app's Railway project (the target's <c>project:service:env</c>), through the
/// public GraphQL API. §11 creation call (from the schema, unverified against a live account): <c>serviceCreate {projectId,
/// environmentId, name: "Postgres", source: {image: "ghcr.io/railwayapp-templates/postgres-ssl:17"}, variables}</c> with the
/// template's variables (<c>POSTGRES_PASSWORD</c> generated by AIDE, <c>PGDATA</c>, and <c>DATABASE_URL</c> over
/// <c>RAILWAY_PRIVATE_DOMAIN</c>), then <c>volumeCreate {projectId, serviceId, environmentId, mountPath:
/// "/var/lib/postgresql/data"}</c>. The preview copies the service into <c>aide-preview</c>: its own variables
/// (<c>variableCollectionUpsert</c>), its own volume and a <c>serviceInstanceDeployV2</c>. The resource id is
/// <c>project:service:env</c>. Apps use <c>DATABASE_URL = ${{Postgres.DATABASE_URL}}</c>. Available once the service's
/// latest deployment in the environment is <c>SUCCESS</c>.
/// </summary>
public sealed class RailwayPostgresProvider(PlatformHttp http) : IDatabaseProvider
{
    public const string Image = "ghcr.io/railwayapp-templates/postgres-ssl:17";
    public const string MountPath = "/var/lib/postgresql/data";

    private const ManagedDatabaseProvider Railway = ManagedDatabaseProvider.Railway;

    public ManagedDatabaseProvider Kind => Railway;

    public async Task<DatabaseSetupResult> SetupAsync(DatabaseAuth auth, DatabaseSetupRequest request, CancellationToken cancellationToken)
    {
        ArgumentNullException.ThrowIfNull(auth);
        ArgumentNullException.ThrowIfNull(request);
        var app = RailwayRules.ParseResourceId(request.Host.RailwayResourceId) ?? throw new DatabaseProviderException(
            DeploymentFailure.Rejected, 400, "Set up the Railway backend (or app) target first: the database goes in its Railway project.", Railway);
        var environmentId = request.Environment == DeploymentEnvironment.Preview
            ? request.Host.RailwayPreviewEnvironmentId ?? throw new DatabaseProviderException(
                DeploymentFailure.Rejected, 400, "The Railway preview environment doesn't exist yet: set up the Railway target first.", Railway)
            : app.ProductionEnvironmentId ?? throw new DatabaseProviderException(
                DeploymentFailure.Rejected, 400, "The Railway target has no production environment; set it up again.", Railway);
        var services = await ServicesAsync(auth, app.ProjectId, cancellationToken);
        if (request.Mode == DatabaseSetupMode.Link)
        {
            var linked = RailwayRules.ParseResourceId(request.LinkResourceId);
            var service = services.FirstOrDefault(s => s.Id == (linked?.ServiceId ?? request.LinkResourceId))
                ?? throw new DatabaseProviderException(DeploymentFailure.NotFound, 404, "That Railway service isn't in the app's Railway project.", Railway);
            return Result(app.ProjectId, service.Id, service.Name, environmentId, false);
        }

        var password = request.Password ?? throw new DatabaseProviderException(DeploymentFailure.Rejected, 400, "A new Railway Postgres needs a password.", Railway);
        var serviceId = services.FirstOrDefault(s => s.Name == ManagedDatabaseRules.RailwayServiceName)?.Id;
        if (serviceId is null)
        {
            var created = await QueryAsync(
                auth,
                "mutation($input: ServiceCreateInput!) { serviceCreate(input: $input) { id name } }",
                new { input = new { projectId = app.ProjectId, environmentId, name = ManagedDatabaseRules.RailwayServiceName, source = new { image = Image }, variables = Variables(password) } },
                cancellationToken);
            serviceId = Text(Property(created, "serviceCreate"), "id")
                ?? throw new DatabaseProviderException(DeploymentFailure.Upstream, null, "Railway created the Postgres service but returned no id.", Railway);
        }
        else
        {
            await QueryAsync(
                auth,
                "mutation($input: VariableCollectionUpsertInput!) { variableCollectionUpsert(input: $input) }",
                new { input = new { projectId = app.ProjectId, environmentId, serviceId, variables = Variables(password), skipDeploys = true } },
                cancellationToken);
        }

        if (!await HasVolumeAsync(auth, app.ProjectId, serviceId, environmentId, cancellationToken))
        {
            await QueryAsync(
                auth,
                "mutation($input: VolumeCreateInput!) { volumeCreate(input: $input) { id } }",
                new { input = new { projectId = app.ProjectId, serviceId, environmentId, mountPath = MountPath } },
                cancellationToken);
        }

        await QueryAsync(
            auth,
            "mutation($serviceId: String!, $environmentId: String!) { serviceInstanceDeployV2(serviceId: $serviceId, environmentId: $environmentId) }",
            new { serviceId, environmentId },
            cancellationToken);
        return Result(app.ProjectId, serviceId, ManagedDatabaseRules.RailwayServiceName, environmentId, true);
    }

    public async Task<DatabasePoll> PollAsync(DatabaseAuth auth, DatabaseRef database, CancellationToken cancellationToken)
    {
        ArgumentNullException.ThrowIfNull(auth);
        ArgumentNullException.ThrowIfNull(database);
        var resource = RailwayRules.ParseResourceId(database.ResourceId) is { ProductionEnvironmentId: not null } r ? r
            : throw new DatabaseProviderException(DeploymentFailure.NotFound, 404, "The Railway Postgres service isn't known.", Railway);
        var data = await QueryAsync(
            auth,
            "query($input: DeploymentListInput!) { deployments(input: $input, first: 1) { edges { node { id status } } } }",
            new { input = new { projectId = resource.ProjectId, serviceId = resource.ServiceId, environmentId = resource.ProductionEnvironmentId } },
            cancellationToken);
        var status = Items(Property(data, "deployments"), "edges").Select(e => Text(Property(e, "node"), "status")).FirstOrDefault();
        var mapped = status?.ToUpperInvariant() switch
        {
            "SUCCESS" => new DatabaseStateMapping(ManagedDatabaseStatus.Available, true),
            "FAILED" or "CRASHED" => new DatabaseStateMapping(ManagedDatabaseStatus.Error, true),
            "REMOVED" => new DatabaseStateMapping(ManagedDatabaseStatus.Removed, true),
            "SLEEPING" => new DatabaseStateMapping(ManagedDatabaseStatus.Paused, true),
            _ => new DatabaseStateMapping(ManagedDatabaseStatus.Provisioning, false),
        };
        var connection = (database.Connection ?? new ManagedDatabaseConnection()) with
        {
            RailwayService = database.Connection?.RailwayService ?? database.Name ?? ManagedDatabaseRules.RailwayServiceName,
            DashboardUrl = Dashboard(resource.ProjectId, resource.ServiceId),
        };
        return new DatabasePoll(mapped.Status, mapped.Terminal, status is null ? "Waiting for the first deployment" : $"Railway deployment {status}", connection);
    }

    public Task<DatabaseLiveState?> ReadStateAsync(DatabaseAuth auth, string resourceId, CancellationToken cancellationToken) =>
        Task.FromResult<DatabaseLiveState?>(null);

    public Task RestoreAsync(DatabaseAuth auth, string resourceId, CancellationToken cancellationToken) =>
        throw new DatabaseProviderException(DeploymentFailure.Rejected, 400, "Railway Postgres has no restore action.", Railway);

    public Task ApplyAuthUrlsAsync(DatabaseAuth auth, string resourceId, string siteUrl, string allowList, CancellationToken cancellationToken) => Task.CompletedTask;

    public Task<IReadOnlyList<AdvisorFinding>> SecurityAdvisorsAsync(DatabaseAuth auth, string resourceId, CancellationToken cancellationToken) =>
        Task.FromResult<IReadOnlyList<AdvisorFinding>>([]);

    /// <summary>The Postgres template's variables; <c>DATABASE_URL</c> resolves over the private network.</summary>
    internal static Dictionary<string, string> Variables(string password) => new(StringComparer.Ordinal)
    {
        ["POSTGRES_USER"] = "postgres",
        ["POSTGRES_PASSWORD"] = password,
        ["POSTGRES_DB"] = "railway",
        ["PGDATA"] = $"{MountPath}/pgdata",
        ["DATABASE_URL"] = "postgresql://${{POSTGRES_USER}}:${{POSTGRES_PASSWORD}}@${{RAILWAY_PRIVATE_DOMAIN}}:5432/${{POSTGRES_DB}}",
    };

    private async Task<bool> HasVolumeAsync(DatabaseAuth auth, string projectId, string serviceId, string environmentId, CancellationToken cancellationToken)
    {
        var data = await QueryAsync(
            auth,
            "query($id: String!) { project(id: $id) { volumes { edges { node { id volumeInstances { edges { node { serviceId environmentId } } } } } } } }",
            new { id = projectId },
            cancellationToken);
        return Nodes(Property(Property(data, "project"), "volumes"))
            .SelectMany(v => Nodes(Property(v, "volumeInstances")))
            .Any(i => Text(i, "serviceId") == serviceId && Text(i, "environmentId") == environmentId);
    }

    private async Task<IReadOnlyList<Deployments.RailwayNode>> ServicesAsync(DatabaseAuth auth, string projectId, CancellationToken cancellationToken)
    {
        var data = await QueryAsync(auth, "query($id: String!) { project(id: $id) { id services { edges { node { id name } } } } }", new { id = projectId }, cancellationToken);
        return [.. Nodes(Property(Property(data, "project"), "services")).Where(n => Text(n, "id") is not null).Select(n => new Deployments.RailwayNode(Text(n, "id")!, Text(n, "name") ?? Text(n, "id")!))];
    }

    private static DatabaseSetupResult Result(string projectId, string serviceId, string name, string environmentId, bool passwordSet) =>
        new(RailwayRules.ResourceId(new RailwayResource(projectId, serviceId, environmentId)), name, null, null, passwordSet, Dashboard(projectId, serviceId));

    private static string Dashboard(string projectId, string serviceId) =>
        $"https://railway.com/project/{Uri.EscapeDataString(projectId)}/service/{Uri.EscapeDataString(serviceId)}";

    private static IEnumerable<JsonElement> Nodes(JsonElement connection) => Items(connection, "edges").Select(e => Property(e, "node"));

    private Task<JsonElement> QueryAsync(DatabaseAuth auth, string query, object? variables, CancellationToken cancellationToken) =>
        DatabaseProviderException.Call(
            Railway,
            async () =>
            {
                using var json = await http.SendAsync(
                    PlatformProvider.Railway, PlatformHosts.RailwayClient, HttpMethod.Post, "graphql/v2", auth.Token, new { query, variables }, cancellationToken);
                var errors = Items(json.RootElement, "errors").ToList();
                if (errors.Count > 0)
                {
                    var message = Text(errors[0], "message") ?? "request failed";
                    var failure = PlatformConnectionRules.ClassifyRailwayError(message);
                    throw new PlatformApiException(failure, failure == PlatformFailure.RateLimited ? 429 : 400, $"Railway: {PlatformHttp.Clean(message)}");
                }

                return Property(json.RootElement, "data").Clone();
            });
}
