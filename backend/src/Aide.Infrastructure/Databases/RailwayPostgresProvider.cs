namespace Aide.Infrastructure.Databases;

/// <summary>
/// FR-152, §4.21 Railway Postgres in the app's Railway project (the target's <c>project:service:env</c>), through the
/// public GraphQL API. §11 creation call (from the schema, unverified against a live account): <c>serviceCreate {projectId,
/// environmentId, name: "Postgres", source: {image: "ghcr.io/railwayapp-templates/postgres-ssl:18"}, variables}</c> with the
/// template's variables (<c>POSTGRES_PASSWORD</c> generated by Tevrin, <c>PGDATA</c>, and <c>DATABASE_URL</c> over
/// <c>RAILWAY_PRIVATE_DOMAIN</c>), then <c>volumeCreate {projectId, serviceId, environmentId, mountPath:
/// "/var/lib/postgresql/data"}</c>. The preview copies the service into <c>aide-preview</c>: its own variables
/// (<c>variableCollectionUpsert</c>), its own volume and a <c>serviceInstanceDeployV2</c>. The resource id is
/// <c>project:service:env</c>. Apps use <c>DATABASE_URL = ${{Postgres.DATABASE_URL}}</c>. Available once the service's
/// latest deployment in the environment is <c>SUCCESS</c>.
/// §4.28: in a group the service goes in the shared project. A standalone one (<see cref="DatabaseHostContext.RailwayStandsAlone"/>)
/// gets its own project (the window's name, without <c>-preview</c>; <c>PLATFORM_RESOURCE_EXISTS</c> on an existing name; the
/// job stores the id at once and resumes from it). Whenever the app isn't in the database's project
/// (<see cref="DatabaseHostContext.RailwayPublicUrl"/>), no private network reaches it, so it has a public URL through <c>tcpProxyCreate {applicationPort:
/// 5432, environmentId, serviceId}</c>: <c>postgresql://user:password@&lt;proxy domain&gt;:&lt;proxyPort&gt;/db</c>. Those
/// fields are in Railway's public schema (introspected 2026-11-01), unverified against a live account (§11 Q5).
/// </summary>
public sealed class RailwayPostgresProvider(PlatformHttp http) : IDatabaseProvider
{
    /// <summary>
    /// FR-195, D-V5-12: every new Railway Postgres is 18, like Tevrin's own (<c>.railway/railway.ts</c>). Only new services and
    /// fresh (volume-less) instances get it: an instance with data keeps its image, since Postgres can't open an older major's
    /// data directory (D-V3-13).
    /// </summary>
    public const string Image = "ghcr.io/railwayapp-templates/postgres-ssl:18";

    /// <summary>
    /// FR-195: the template's volume path for every major, 18 included. Unlike <c>postgres:18</c> (default <c>PGDATA</c>
    /// <c>/var/lib/postgresql/18/docker</c>), the postgres-ssl image's <c>wrapper.sh</c> exits unless the Railway volume is
    /// mounted here and <c>PGDATA</c> starts with it, and its Dockerfile sets no <c>PGDATA</c>: Tevrin sets <c>PGDATA</c> below.
    /// </summary>
    public const string MountPath = "/var/lib/postgresql/data";

    private static readonly string PostgresPortText = ManagedDatabaseRules.PostgresPort.ToString(System.Globalization.CultureInfo.InvariantCulture);

    private const ManagedDatabaseProvider Railway = ManagedDatabaseProvider.Railway;

    public ManagedDatabaseProvider Kind => Railway;

    public async Task<DatabaseSetupResult> SetupAsync(DatabaseAuth auth, DatabaseSetupRequest request, CancellationToken cancellationToken)
    {
        ArgumentNullException.ThrowIfNull(auth);
        ArgumentNullException.ThrowIfNull(request);
        var (projectId, environmentId) = request.Host.SharedProjectId is not null || request.Host.RailwayStandsAlone
            ? await OwnPlacementAsync(auth, request, cancellationToken)
            : TargetPlacement(request);
        var services = await ServicesAsync(auth, projectId, cancellationToken);
        if (request.Mode == DatabaseSetupMode.Link)
        {
            var linked = RailwayRules.ParseResourceId(request.LinkResourceId);
            var service = services.FirstOrDefault(s => s.Id == (linked?.ServiceId ?? request.LinkResourceId))
                ?? throw new DatabaseProviderException(DeploymentFailure.NotFound, 404, "That Railway service isn't in the app's Railway project.", Railway);

            // §4.28: aide-preview was copied with skipInitialDeploys, so a linked service's preview instance has no volume
            // and never ran: it gets its own password and volume, and a deployment. Production is the Owner's, as it stands.
            if (request.Environment != DeploymentEnvironment.Preview || !(request.Host.SharedProjectId is not null || request.Host.RailwayStandsAlone))
            {
                return Result(projectId, service.Id, service.Name, environmentId, false);
            }

            var provisioned = await ProvisionInstanceAsync(auth, projectId, service.Id, environmentId, request.Password, cancellationToken);
            return Result(projectId, service.Id, service.Name, environmentId, provisioned);
        }

        var password = request.Password ?? throw new DatabaseProviderException(DeploymentFailure.Rejected, 400, "A new Railway Postgres needs a password.", Railway);
        var serviceId = services.FirstOrDefault(s => s.Name == ManagedDatabaseRules.RailwayServiceName)?.Id;
        bool? hasVolume = null;
        if (serviceId is null)
        {
            var created = await QueryAsync(
                auth,
                "mutation($input: ServiceCreateInput!) { serviceCreate(input: $input) { id name } }",
                new { input = new { projectId, environmentId, name = ManagedDatabaseRules.RailwayServiceName, source = new { image = Image }, variables = Variables(password) } },
                cancellationToken);
            serviceId = Text(Property(created, "serviceCreate"), "id")
                ?? throw new DatabaseProviderException(DeploymentFailure.Upstream, null, "Railway created the Postgres service but returned no id.", Railway);
        }
        else
        {
            hasVolume = await HasVolumeAsync(auth, projectId, serviceId, environmentId, cancellationToken);
            if (hasVolume == false && request.Environment == DeploymentEnvironment.Preview)
            {
                // FR-195: aide-preview's fresh copy of the Postgres AIDE created (Create mode) has no data yet, so it starts on
                // 18. Production adoption never changes the image (the service may be the Owner's), and an instance with a
                // volume is never touched: its image stays what its data was made with.
                await QueryAsync(
                    auth,
                    "mutation($serviceId: String!, $environmentId: String, $input: ServiceInstanceUpdateInput!) { serviceInstanceUpdate(serviceId: $serviceId, environmentId: $environmentId, input: $input) }",
                    new { serviceId, environmentId, input = new { source = new { image = Image } } },
                    cancellationToken);
            }

            await QueryAsync(
                auth,
                "mutation($input: VariableCollectionUpsertInput!) { variableCollectionUpsert(input: $input) }",
                new { input = new { projectId, environmentId, serviceId, variables = Variables(password), skipDeploys = true } },
                cancellationToken);
        }

        if (!(hasVolume ?? await HasVolumeAsync(auth, projectId, serviceId, environmentId, cancellationToken)))
        {
            await QueryAsync(
                auth,
                "mutation($input: VolumeCreateInput!) { volumeCreate(input: $input) { id } }",
                new { input = new { projectId, serviceId, environmentId, mountPath = MountPath } },
                cancellationToken);
        }

        await QueryAsync(
            auth,
            "mutation($serviceId: String!, $environmentId: String!) { serviceInstanceDeployV2(serviceId: $serviceId, environmentId: $environmentId) }",
            new { serviceId, environmentId },
            cancellationToken);
        return Result(projectId, serviceId, ManagedDatabaseRules.RailwayServiceName, environmentId, true);
    }

    /// <summary>
    /// The preview instance of a linked service: unless it already has its volume (it was provisioned, or is a service of its
    /// own), it gets the variables, the volume and a deployment. Whether a password was set.
    /// </summary>
    private async Task<bool> ProvisionInstanceAsync(DatabaseAuth auth, string projectId, string serviceId, string environmentId, string? password, CancellationToken cancellationToken)
    {
        var fresh = !await HasVolumeAsync(auth, projectId, serviceId, environmentId, cancellationToken);
        if (fresh)
        {
            await QueryAsync(
                auth,
                "mutation($input: VariableCollectionUpsertInput!) { variableCollectionUpsert(input: $input) }",
                new { input = new { projectId, environmentId, serviceId, variables = Variables(password ?? throw new DatabaseProviderException(DeploymentFailure.Rejected, 400, "A new Railway Postgres needs a password.", Railway)), skipDeploys = true } },
                cancellationToken);
            await QueryAsync(
                auth,
                "mutation($input: VolumeCreateInput!) { volumeCreate(input: $input) { id } }",
                new { input = new { projectId, serviceId, environmentId, mountPath = MountPath } },
                cancellationToken);
        }

        await QueryAsync(
            auth,
            "mutation($serviceId: String!, $environmentId: String!) { serviceInstanceDeployV2(serviceId: $serviceId, environmentId: $environmentId) }",
            new { serviceId, environmentId },
            cancellationToken);
        return fresh;
    }

    /// <summary>§4.21 0.4.0: the app's Railway project, from its target.</summary>
    private static (string ProjectId, string EnvironmentId) TargetPlacement(DatabaseSetupRequest request)
    {
        var app = RailwayRules.ParseResourceId(request.Host.RailwayResourceId) ?? throw new DatabaseProviderException(
            DeploymentFailure.Rejected, 400, "Set up the Railway backend (or app) target first: the database goes in its Railway project.", Railway);
        var environmentId = request.Environment == DeploymentEnvironment.Preview
            ? request.Host.RailwayPreviewEnvironmentId ?? throw new DatabaseProviderException(
                DeploymentFailure.Rejected, 400, "The Railway preview environment doesn't exist yet: set up the Railway target first.", Railway)
            : app.ProductionEnvironmentId ?? throw new DatabaseProviderException(
                DeploymentFailure.Rejected, 400, "The Railway target has no production environment; set it up again.", Railway);
        return (app.ProjectId, environmentId);
    }

    /// <summary>§4.28: the shared or standalone project, with the environment made if it isn't there yet (no target has to exist).</summary>
    private async Task<(string ProjectId, string EnvironmentId)> OwnPlacementAsync(DatabaseAuth auth, DatabaseSetupRequest request, CancellationToken cancellationToken)
    {
        var projectId = request.Host.SharedProjectId ?? request.Host.RailwayOwnProjectId;
        if (projectId is null && request.Mode == DatabaseSetupMode.Link)
        {
            projectId = RailwayRules.ParseResourceId(request.LinkResourceId)?.ProjectId ?? await ProjectOfServiceAsync(auth, request.LinkResourceId!, cancellationToken);
        }

        if (projectId is null)
        {
            throw new DatabaseProviderException(DeploymentFailure.Rejected, 400, "The standalone Railway database has no project yet.", Railway);
        }

        var environments = await EnvironmentsAsync(auth, projectId, cancellationToken);
        var production = environments.FirstOrDefault(e => e.Name == RailwayRules.ProductionEnvironmentName) ?? (environments.Count > 0 ? environments[0] : null)
            ?? throw new DatabaseProviderException(DeploymentFailure.Upstream, null, "The Railway project has no environment.", Railway);
        if (request.Environment != DeploymentEnvironment.Preview)
        {
            return (projectId, production.Id);
        }

        if (environments.FirstOrDefault(e => e.Name == RailwayRules.PreviewEnvironmentName) is { } preview)
        {
            return (projectId, preview.Id);
        }

        var created = await QueryAsync(
            auth,
            "mutation($input: EnvironmentCreateInput!) { environmentCreate(input: $input) { id name } }",
            new { input = new { projectId, name = RailwayRules.PreviewEnvironmentName, sourceEnvironmentId = production.Id, skipInitialDeploys = true } },
            cancellationToken);
        return (projectId, Text(Property(created, "environmentCreate"), "id")
            ?? throw new DatabaseProviderException(DeploymentFailure.Upstream, null, "Railway created the preview environment but returned no id.", Railway));
    }

    public async Task<string?> CreateOwnProjectAsync(DatabaseAuth auth, string name, CancellationToken cancellationToken)
    {
        ArgumentNullException.ThrowIfNull(auth);
        ArgumentNullException.ThrowIfNull(name);
        var workspace = auth.AccountId ?? throw new DatabaseProviderException(
            DeploymentFailure.Rejected, 400, "The Railway connection has no workspace; give its workspace id in Settings → Connections.", Railway);
        var projects = await QueryAsync(auth, "query($id: String!) { projects(workspaceId: $id, first: 100) { edges { node { id name } } } }", new { id = workspace }, cancellationToken);
        if (Nodes(Property(projects, "projects")).Any(n => Text(n, "name") == name))
        {
            throw new DatabaseProviderException(DeploymentFailure.ResourceExists, 409, $"Railway already has a project named {name}. Link it instead, or choose another name.", Railway);
        }

        var data = await QueryAsync(
            auth,
            "mutation($input: ProjectCreateInput!) { projectCreate(input: $input) { id name } }",
            new { input = new { name, workspaceId = workspace, prDeploys = false, defaultEnvironmentName = RailwayRules.ProductionEnvironmentName } },
            cancellationToken);
        return Text(Property(data, "projectCreate"), "id")
            ?? throw new DatabaseProviderException(DeploymentFailure.Upstream, null, "Railway created the project but returned no id.", Railway);
    }

    /// <summary>The workspace project holding a linked service (the picker's id is the service's).</summary>
    private async Task<string> ProjectOfServiceAsync(DatabaseAuth auth, string serviceId, CancellationToken cancellationToken)
    {
        var workspace = auth.AccountId ?? throw new DatabaseProviderException(
            DeploymentFailure.Rejected, 400, "The Railway connection has no workspace; give its workspace id in Settings → Connections.", Railway);
        var data = await QueryAsync(
            auth, "query($id: String!) { projects(workspaceId: $id, first: 100) { edges { node { id services { edges { node { id } } } } } } }", new { id = workspace }, cancellationToken);
        foreach (var project in Nodes(Property(data, "projects")))
        {
            if (Nodes(Property(project, "services")).Any(s => Text(s, "id") == serviceId) && Text(project, "id") is { } id)
            {
                return id;
            }
        }

        throw new DatabaseProviderException(DeploymentFailure.NotFound, 404, "This connection can't reach that Railway service.", Railway);
    }

    /// <summary>§4.28: the public URL of a standalone database through its TCP proxy (made once). The password is the one Tevrin generated, else the service's.</summary>
    private async Task<string> PublicUrlAsync(DatabaseAuth auth, RailwayResource resource, string? password, CancellationToken cancellationToken)
    {
        var environmentId = resource.ProductionEnvironmentId!;
        var proxies = await QueryAsync(
            auth,
            "query($environmentId: String!, $serviceId: String!) { tcpProxies(environmentId: $environmentId, serviceId: $serviceId) { domain proxyPort applicationPort } }",
            new { environmentId, serviceId = resource.ServiceId },
            cancellationToken);
        var proxy = Items(proxies, "tcpProxies").FirstOrDefault(p => Text(p, "applicationPort") == PostgresPortText);
        if (Text(proxy, "domain") is null)
        {
            var created = await QueryAsync(
                auth,
                "mutation($input: TCPProxyCreateInput!) { tcpProxyCreate(input: $input) { domain proxyPort applicationPort } }",
                new { input = new { applicationPort = ManagedDatabaseRules.PostgresPort, environmentId, serviceId = resource.ServiceId } },
                cancellationToken);
            proxy = Property(created, "tcpProxyCreate");
        }

        var variables = Property(await QueryAsync(
            auth,
            "query($projectId: String!, $environmentId: String!, $serviceId: String) { variables(projectId: $projectId, environmentId: $environmentId, serviceId: $serviceId) }",
            new { projectId = resource.ProjectId, environmentId, serviceId = resource.ServiceId },
            cancellationToken), "variables");
        var secret = password ?? Text(variables, "POSTGRES_PASSWORD") ?? Text(variables, "PGPASSWORD");
        if (Text(proxy, "domain") is not { } domain || !int.TryParse(Text(proxy, "proxyPort"), System.Globalization.CultureInfo.InvariantCulture, out var port) || secret is null)
        {
            throw new DatabaseProviderException(DeploymentFailure.Upstream, null, "Railway returned no public address for the database yet.", Railway);
        }

        return ManagedDatabaseRules.PoolerUrl(domain, Text(variables, "POSTGRES_USER") ?? "postgres", secret, port, Text(variables, "POSTGRES_DB") ?? "railway");
    }

    public async Task<DatabasePoll> PollAsync(DatabaseAuth auth, DatabaseRef database, CancellationToken cancellationToken)
    {
        ArgumentNullException.ThrowIfNull(auth);
        ArgumentNullException.ThrowIfNull(database);
        var resource = RailwayRules.ParseResourceId(database.ResourceId) is { ProductionEnvironmentId: not null } r ? r
            : throw new DatabaseProviderException(DeploymentFailure.NotFound, 404, "The Railway Postgres service isn't known.", Railway);
        var data = await QueryAsync(
            auth,
            "query($input: DeploymentListInput!) { deployments(input: $input, first: 1) { edges { node { id status } } } }",
            new { input = new { projectId = resource.ProjectId, serviceId = resource.ServiceId, environmentId = resource.ProductionEnvironmentId } },
            cancellationToken);
        var status = Items(Property(data, "deployments"), "edges").Select(e => Text(Property(e, "node"), "status")).FirstOrDefault();
        var mapped = status?.ToUpperInvariant() switch
        {
            "SUCCESS" => new DatabaseStateMapping(ManagedDatabaseStatus.Available, true),
            "FAILED" or "CRASHED" => new DatabaseStateMapping(ManagedDatabaseStatus.Error, true),
            "REMOVED" => new DatabaseStateMapping(ManagedDatabaseStatus.Removed, true),
            "SLEEPING" => new DatabaseStateMapping(ManagedDatabaseStatus.Paused, true),
            _ => new DatabaseStateMapping(ManagedDatabaseStatus.Provisioning, false),
        };
        var connection = (database.Connection ?? new ManagedDatabaseConnection()) with
        {
            RailwayService = database.Connection?.RailwayService ?? database.Name ?? ManagedDatabaseRules.RailwayServiceName,
            DashboardUrl = Dashboard(resource.ProjectId, resource.ServiceId),
        };
        if (database.Host.RailwayPublicUrl && mapped.Status == ManagedDatabaseStatus.Available)
        {
            connection = connection with { Url = await PublicUrlAsync(auth, resource, database.Password, cancellationToken), RailwaySeparateProject = true };
        }

        return new DatabasePoll(mapped.Status, mapped.Terminal, status is null ? "Waiting for the first deployment" : $"Railway deployment {status}", connection);
    }

    public Task<DatabaseLiveState?> ReadStateAsync(DatabaseAuth auth, string resourceId, CancellationToken cancellationToken) =>
        Task.FromResult<DatabaseLiveState?>(null);

    public Task RestoreAsync(DatabaseAuth auth, string resourceId, CancellationToken cancellationToken) =>
        throw new DatabaseProviderException(DeploymentFailure.Rejected, 400, "Railway Postgres has no restore action.", Railway);

    public Task ApplyAuthUrlsAsync(DatabaseAuth auth, string resourceId, string siteUrl, string allowList, CancellationToken cancellationToken) => Task.CompletedTask;

    public Task<IReadOnlyList<AdvisorFinding>> SecurityAdvisorsAsync(DatabaseAuth auth, string resourceId, CancellationToken cancellationToken) =>
        Task.FromResult<IReadOnlyList<AdvisorFinding>>([]);

    /// <summary>The Postgres template's variables; <c>DATABASE_URL</c> resolves over the private network.</summary>
    internal static Dictionary<string, string> Variables(string password) => new(StringComparer.Ordinal)
    {
        ["POSTGRES_USER"] = "postgres",
        ["POSTGRES_PASSWORD"] = password,
        ["POSTGRES_DB"] = "railway",
        ["PGDATA"] = $"{MountPath}/pgdata",
        ["DATABASE_URL"] = "postgresql://${{POSTGRES_USER}}:${{POSTGRES_PASSWORD}}@${{RAILWAY_PRIVATE_DOMAIN}}:5432/${{POSTGRES_DB}}",
    };

    private async Task<bool> HasVolumeAsync(DatabaseAuth auth, string projectId, string serviceId, string environmentId, CancellationToken cancellationToken)
    {
        var data = await QueryAsync(
            auth,
            "query($id: String!) { project(id: $id) { volumes { edges { node { id volumeInstances { edges { node { serviceId environmentId } } } } } } } }",
            new { id = projectId },
            cancellationToken);
        return Nodes(Property(Property(data, "project"), "volumes"))
            .SelectMany(v => Nodes(Property(v, "volumeInstances")))
            .Any(i => Text(i, "serviceId") == serviceId && Text(i, "environmentId") == environmentId);
    }

    private async Task<IReadOnlyList<Deployments.RailwayNode>> EnvironmentsAsync(DatabaseAuth auth, string projectId, CancellationToken cancellationToken)
    {
        var data = await QueryAsync(auth, "query($id: String!) { project(id: $id) { id environments { edges { node { id name } } } } }", new { id = projectId }, cancellationToken);
        return [.. Nodes(Property(Property(data, "project"), "environments")).Where(n => Text(n, "id") is not null).Select(n => new Deployments.RailwayNode(Text(n, "id")!, Text(n, "name") ?? string.Empty))];
    }

    private async Task<IReadOnlyList<Deployments.RailwayNode>> ServicesAsync(DatabaseAuth auth, string projectId, CancellationToken cancellationToken)
    {
        var data = await QueryAsync(auth, "query($id: String!) { project(id: $id) { id services { edges { node { id name } } } } }", new { id = projectId }, cancellationToken);
        return [.. Nodes(Property(Property(data, "project"), "services")).Where(n => Text(n, "id") is not null).Select(n => new Deployments.RailwayNode(Text(n, "id")!, Text(n, "name") ?? Text(n, "id")!))];
    }

    private static DatabaseSetupResult Result(string projectId, string serviceId, string name, string environmentId, bool passwordSet) =>
        new(RailwayRules.ResourceId(new RailwayResource(projectId, serviceId, environmentId)), name, null, null, passwordSet, Dashboard(projectId, serviceId));

    private static string Dashboard(string projectId, string serviceId) =>
        $"https://railway.com/project/{Uri.EscapeDataString(projectId)}/service/{Uri.EscapeDataString(serviceId)}";

    private static IEnumerable<JsonElement> Nodes(JsonElement connection) => Items(connection, "edges").Select(e => Property(e, "node"));

    private Task<JsonElement> QueryAsync(DatabaseAuth auth, string query, object? variables, CancellationToken cancellationToken) =>
        DatabaseProviderException.Call(
            Railway,
            async () =>
            {
                using var json = await http.SendAsync(
                    PlatformProvider.Railway, PlatformHosts.RailwayClient, HttpMethod.Post, "graphql/v2", auth.Token, new { query, variables }, cancellationToken);
                var errors = Items(json.RootElement, "errors").ToList();
                if (errors.Count > 0)
                {
                    var message = Text(errors[0], "message") ?? "request failed";
                    var failure = PlatformConnectionRules.ClassifyRailwayError(message);
                    throw new PlatformApiException(failure, failure == PlatformFailure.RateLimited ? 429 : 400, $"Railway: {PlatformHttp.Clean(message)}");
                }

                return Property(json.RootElement, "data").Clone();
            });
}
