import { errorMessage, isApiError, isRestoreReason, restoreNotAllowedMessage } from '../../lib/errors'
import { producingStageLabel, type RestoreBlock } from '../stages/stage-model'
import type { ArtifactType } from './artifacts-api'

/** FR-58: copy for a failed restore, using the RESTORE_NOT_ALLOWED `reason` when the server gives one. */
export function restoreErrorMessage(error: unknown, type: ArtifactType): string {
  if (isApiError(error, 'RESTORE_NOT_ALLOWED') && isRestoreReason(error.reason)) {
    return restoreNotAllowedMessage(error.reason, producingStageLabel(type))
  }
  return errorMessage(error, 'restoreArtifact')
}

/** FR-58: why the restore action is hidden, in words (the API reasons plus the never-restorable codebase summary). */
export function restoreBlockMessage(block: RestoreBlock, type: ArtifactType): string {
  if (block === 'not_restorable') {
    return "The codebase summary is generated by the Repository Analyst and locked automatically, so its versions can't be restored."
  }
  return restoreNotAllowedMessage(block, producingStageLabel(type))
}
